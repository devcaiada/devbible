#!/usr/bin/env node

/**
 * Renders a `devbible audit --json` report as Markdown.
 * Used by the GitHub Action for the pull request comment and the job summary.
 *
 * Usage: node scripts/report-markdown.js <report.json>
 */

const fs = require('fs');

const reportPath = process.argv[2];
if (!reportPath) {
  console.error('Usage: node scripts/report-markdown.js <report.json>');
  process.exit(1);
}

const report = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
const REPO_URL = 'https://github.com/devcaiada/devbible';

const STATUS = {
  PASS: '✅ Pass',
  WARN: '⚠️ Warning',
  FAIL: '❌ Fail',
};

const tier = (level) => (level === 1 ? 'Level 1' : level === 2 ? 'Level 2' : 'Level 3');

const rows = report.items.map(
  (item) =>
    `| ${item.id} | ${tier(item.level)} | ${STATUS[item.status] || item.status} | [${item.name}](${REPO_URL}/blob/main/checklist/${item.file}) |`
);

// Same ordering the CLI uses: failures first, then warnings, at most three.
const next = [
  ...report.items.filter((i) => i.status === 'FAIL'),
  ...report.items.filter((i) => i.status === 'WARN'),
]
  .slice(0, 3)
  .map(
    (item) =>
      `- ${item.status === 'FAIL' ? '**Fix**' : 'Improve'} [${item.id}] [${item.name}](${REPO_URL}/blob/main/checklist/${item.file})`
  );

const out = [
  '<!-- devbible-audit -->',
  '## 🛡️ DevBible Production-Readiness Audit',
  '',
  `**Score: ${report.score}%** · ${report.maturity}`,
  '',
  `✅ ${report.passed} passed · ⚠️ ${report.warnings} ${report.warnings === 1 ? 'warning' : 'warnings'} · ❌ ${report.failed} failed`,
  '',
  '| # | Tier | Status | Checklist item |',
  '|---|------|--------|----------------|',
  ...rows,
  '',
];

if (next.length > 0) {
  out.push('**Top next actions**', '', ...next, '');
}

out.push(
  `<sub>Static heuristics, not a guarantee. Generated by [DevBible](${REPO_URL}) v${report.version}.</sub>`
);

process.stdout.write(out.join('\n') + '\n');
